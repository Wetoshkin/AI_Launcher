    public static IReadOnlyCollection<string> Ids => Items.Keys.ToArray();

    public static bool Contains(string id) => Items.ContainsKey(id);

    public static ParameterHelp Get(string id)
    {
        if (Items.TryGetValue(id, out var help)) return help;
        throw new KeyNotFoundException($"Unknown parameter help id: {id}");
    }

    public static bool TryGet(string id, out ParameterHelp help) => Items.TryGetValue(id, out help!);
